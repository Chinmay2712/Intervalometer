// Generates every app icon and launch image from assets/branding/logo_source.jpg.
//
//   dart run tool/make_icons.dart
//
// Icons are full-bleed: the logo's own background colour fills the whole
// shape, so circle, squircle and rounded-square launchers never show white
// borders or a small square inside the mask.
import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:image/image.dart' as img;

const _source = 'assets/branding/logo_source.jpg';
const _res = 'android/app/src/main/res';
const _iosIcons = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
const _iosLaunch = 'ios/Runner/Assets.xcassets/LaunchImage.imageset';

/// Logo width as a share of the icon. iOS and legacy Android show the whole
/// square; adaptive icons lose the outer third to the mask, so the logo is
/// smaller there to stay inside Android's 66 dp safe circle.
const _squareShare = 0.58;
const _adaptiveShare = 0.42;
const _roundShare = 0.52;

late img.Image _src;
late img.ColorRgb8 _bg;
late Rectangle<int> _logo;

void main() {
  _src = img.decodeJpg(File(_source).readAsBytesSync())!;
  _bg = _backgroundColour();
  _logo = _logoBounds();
  stdout.writeln('source ${_src.width}x${_src.height}, background '
      '#${_hex(_bg.r)}${_hex(_bg.g)}${_hex(_bg.b)}, logo $_logo');

  // ---------------------------------------------------------------- Android
  const densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};
  for (final e in densities.entries) {
    final dir = '$_res/mipmap-${e.key}';
    Directory(dir).createSync(recursive: true);
    final legacy = (48 * e.value).round();
    final layer = (108 * e.value).round();
    _png('$dir/ic_launcher.png', _square(legacy, _squareShare));
    _png('$dir/ic_launcher_round.png', _circle(legacy, _roundShare));
    _png('$dir/ic_launcher_foreground.png', _square(layer, _adaptiveShare));
    _png('$dir/ic_launcher_monochrome.png', _monochrome(layer, _adaptiveShare));
    _png('$dir/launch_image.png', _square((96 * e.value).round(), 1 / 1.25));
  }
  Directory('$_res/mipmap-anydpi-v26').createSync(recursive: true);
  const adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.dart. Full-bleed: the background layer is the
     logo's own colour, so any launcher mask is filled edge to edge. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
''';
  File('$_res/mipmap-anydpi-v26/ic_launcher.xml').writeAsStringSync(adaptive);
  File('$_res/mipmap-anydpi-v26/ic_launcher_round.xml').writeAsStringSync(adaptive);
  Directory('$_res/values').createSync(recursive: true);
  File('$_res/values/ic_launcher_colors.xml').writeAsStringSync('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.dart -->
<resources>
    <color name="ic_launcher_background">#${_hex(_bg.r)}${_hex(_bg.g)}${_hex(_bg.b)}</color>
</resources>
''');

  // ---------------------------------------------------------------- iOS
  final contents = jsonDecode(File('$_iosIcons/Contents.json').readAsStringSync()) as Map<String, dynamic>;
  for (final i in (contents['images'] as List).cast<Map<String, dynamic>>()) {
    final pt = double.parse((i['size'] as String).split('x').first);
    final scale = double.parse((i['scale'] as String).replaceAll('x', ''));
    // iOS rejects icons with an alpha channel.
    _png('$_iosIcons/${i['filename']}', _square((pt * scale).round(), _squareShare), opaque: true);
  }
  for (final (name, px) in const [('LaunchImage.png', 128), ('LaunchImage@2x.png', 256), ('LaunchImage@3x.png', 384)]) {
    _png('$_iosLaunch/$name', _square(px, 1 / 1.25), opaque: true);
  }
  stdout.writeln('done');
}

// ------------------------------------------------------------------ helpers

String _hex(num v) => v.toInt().toRadixString(16).padLeft(2, '0').toUpperCase();

double _lum(img.Pixel p) => 0.299 * p.r + 0.587 * p.g + 0.114 * p.b;

/// Median of the outermost pixels.
img.ColorRgb8 _backgroundColour() {
  final rs = <num>[], gs = <num>[], bs = <num>[];
  void add(int x, int y) {
    final p = _src.getPixel(x, y);
    rs.add(p.r);
    gs.add(p.g);
    bs.add(p.b);
  }

  for (var x = 0; x < _src.width; x += 2) {
    add(x, 0);
    add(x, _src.height - 1);
  }
  for (var y = 0; y < _src.height; y += 2) {
    add(0, y);
    add(_src.width - 1, y);
  }
  int median(List<num> v) => (v..sort())[v.length ~/ 2].toInt();
  return img.ColorRgb8(median(rs), median(gs), median(bs));
}

/// Box around the bright (white) logo pixels.
Rectangle<int> _logoBounds() {
  var x0 = _src.width, y0 = _src.height, x1 = 0, y1 = 0;
  for (final p in _src) {
    if (_lum(p) > 140) {
      x0 = min(x0, p.x);
      y0 = min(y0, p.y);
      x1 = max(x1, p.x);
      y1 = max(y1, p.y);
    }
  }
  return Rectangle(x0, y0, x1 - x0 + 1, y1 - y0 + 1);
}

/// Square of [size] px, background colour edge to edge, logo centred at
/// [share] of the width. Areas outside the source are filled with the
/// background colour.
img.Image _square(int size, double share) {
  final logoSide = max(_logo.width, _logo.height);
  final crop = logoSide / share; // source pixels covered by the icon
  final cx = _logo.left + _logo.width / 2, cy = _logo.top + _logo.height / 2;
  final scale = crop / size;
  final out = img.Image(width: size, height: size, numChannels: 4);
  for (var y = 0; y < size; y++) {
    for (var x = 0; x < size; x++) {
      final sx = cx - crop / 2 + (x + 0.5) * scale;
      final sy = cy - crop / 2 + (y + 0.5) * scale;
      out.setPixel(x, y, _sample(sx, sy, scale));
    }
  }
  return out;
}

/// Average of the source pixels under one output pixel (smooth downscale).
img.Color _sample(double sx, double sy, double scale) {
  final r = max(0.5, scale / 2);
  var n = 0;
  double tr = 0, tg = 0, tb = 0;
  final step = max(1.0, r / 3);
  for (var dy = -r; dy <= r; dy += step) {
    for (var dx = -r; dx <= r; dx += step) {
      final x = (sx + dx).floor(), y = (sy + dy).floor();
      num pr, pg, pb;
      if (x < 0 || y < 0 || x >= _src.width || y >= _src.height) {
        pr = _bg.r;
        pg = _bg.g;
        pb = _bg.b;
      } else {
        final p = _src.getPixel(x, y);
        pr = p.r;
        pg = p.g;
        pb = p.b;
      }
      tr += pr;
      tg += pg;
      tb += pb;
      n++;
    }
  }
  return img.ColorRgba8((tr / n).round(), (tg / n).round(), (tb / n).round(), 255);
}

/// Legacy round icon: the square icon cut to a circle (anti-aliased edge).
img.Image _circle(int size, double share) {
  final sq = _square(size, share);
  final c = size / 2;
  for (final p in sq) {
    final d = sqrt(pow(p.x + 0.5 - c, 2) + pow(p.y + 0.5 - c, 2));
    p.a = (255 * (c - d + 0.5).clamp(0, 1)).round();
  }
  return sq;
}

/// Android 13 themed icon: the white parts of the logo as a single-colour
/// mask on transparent.
img.Image _monochrome(int size, double share) {
  final sq = _square(size, share);
  for (final p in sq) {
    final a = ((_lum(p) - 60) * 255 / 140).clamp(0, 255).round();
    p
      ..r = 255
      ..g = 255
      ..b = 255
      ..a = a;
  }
  return sq;
}

void _png(String path, img.Image im, {bool opaque = false}) {
  final out = opaque ? im.convert(numChannels: 3) : im;
  File(path).writeAsBytesSync(img.encodePng(out));
}
